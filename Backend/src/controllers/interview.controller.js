const interviewReportModel = require("../models/interviewReport.model");
const { generateInterviewReportService } = require("../services/ai.service");

/**
 * @name generateReportController
 * @description Generates a new interview report using Gemini AI and saves it to MongoDB.
 * @access Private
 */
async function generateReportController(req, res) {
    try {
        const { jobDescription, resume, selfDescription } = req.body;

        if (!jobDescription || !jobDescription.trim()) {
            return res.status(400).json({
                message: "Job description is required"
            });
        }

        const userId = req.user.id;

        // Call Gemini AI Service
        const aiResponse = await generateInterviewReportService({
            jobDescription,
            resume,
            selfDescription
        });

        // Save report to database
        const report = await interviewReportModel.create({
            user: userId,
            jobDescription,
            resume: resume || "",
            selfDescription: selfDescription || "",
            matchScore: aiResponse.matchScore || 70,
            technicalQuestions: aiResponse.technicalQuestions || [],
            behavioralQuestions: aiResponse.behavioralQuestions || [],
            skillGaps: aiResponse.skillGaps || [],
            preparationPlan: aiResponse.preparationPlan || []
        });

        return res.status(201).json({
            message: "Interview report generated successfully",
            report
        });
    } catch (error) {
        console.error("Error in generateReportController:", error);
        return res.status(500).json({
            message: "Failed to generate interview report",
            error: error.message
        });
    }
}

/**
 * @name getUserReportsController
 * @description Retrieves all interview reports generated by the authenticated user.
 * @access Private
 */
async function getUserReportsController(req, res) {
    try {
        const userId = req.user.id;
        const reports = await interviewReportModel.find({ user: userId }).sort({ createdAt: -1 });

        return res.status(200).json({
            message: "Reports retrieved successfully",
            reports
        });
    } catch (error) {
        console.error("Error in getUserReportsController:", error);
        return res.status(500).json({
            message: "Failed to retrieve reports",
            error: error.message
        });
    }
}

/**
 * @name getReportByIdController
 * @description Retrieves a single interview report by ID for the authenticated user.
 * @access Private
 */
async function getReportByIdController(req, res) {
    try {
        const { id } = req.params;
        const userId = req.user.id;

        const report = await interviewReportModel.findOne({ _id: id, user: userId });

        if (!report) {
            return res.status(404).json({
                message: "Interview report not found"
            });
        }

        return res.status(200).json({
            message: "Report retrieved successfully",
            report
        });
    } catch (error) {
        console.error("Error in getReportByIdController:", error);
        return res.status(500).json({
            message: "Failed to retrieve report",
            error: error.message
        });
    }
}

/**
 * @name deleteReportController
 * @description Deletes an interview report by ID for the authenticated user.
 * @access Private
 */
async function deleteReportController(req, res) {
    try {
        const { id } = req.params;
        const userId = req.user.id;

        const report = await interviewReportModel.findOneAndDelete({ _id: id, user: userId });

        if (!report) {
            return res.status(404).json({
                message: "Interview report not found or unauthorized"
            });
        }

        return res.status(200).json({
            message: "Interview report deleted successfully"
        });
    } catch (error) {
        console.error("Error in deleteReportController:", error);
        return res.status(500).json({
            message: "Failed to delete report",
            error: error.message
        });
    }
}

module.exports = {
    generateReportController,
    getUserReportsController,
    getReportByIdController,
    deleteReportController
};
